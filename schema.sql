CREATE TABLE IF NOT EXISTS push_tokens_fcm (
  id SERIAL PRIMARY KEY, token TEXT UNIQUE NOT NULL, aktif BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS push_subscriptions (
  id SERIAL PRIMARY KEY, endpoint TEXT UNIQUE NOT NULL, p256dh TEXT NOT NULL, auth TEXT NOT NULL, aktif BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS notif_log (
  id SERIAL PRIMARY KEY, ticker TEXT NOT NULL, tipe TEXT NOT NULL, terkirim_pada TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS predictions (
  id SERIAL PRIMARY KEY, ticker TEXT NOT NULL, date TEXT NOT NULL,
  skor INTEGER, sinyal TEXT, harga REAL, UNIQUE(ticker, date)
);